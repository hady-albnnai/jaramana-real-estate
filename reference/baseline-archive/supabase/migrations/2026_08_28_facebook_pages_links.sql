UPDATE public.app_config
SET value = jsonb_set(
      jsonb_set(
        value,
        '{txts,facebook}',
        '"https://www.facebook.com/profile.php?id=61593796835750"'::jsonb,
        true
      ),
      '{txts,socialPages,facebook2}',
      '"https://www.facebook.com/profile.php?id=61592278445595"'::jsonb,
      true
    )
WHERE key = 'main';
