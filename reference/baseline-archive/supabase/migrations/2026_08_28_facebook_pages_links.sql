--   • الصفحة الأولى «المكتب العقاري الالكتروني» (Page ID 61592278445595) —
--     الحساب المنشأ عبر نيجيريا؛ استُعيدت السيطرة عليه بتغيير كلمة السر.
--   • الصفحة الثانية «المكتب العقاري الالكتروني ـ السويداء»
